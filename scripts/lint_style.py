def header_block(path):
    name = os.path.basename(path)
    stem = os.path.splitext(name)[0]
    words = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", stem).replace("_", " ").split()
    desc = " ".join(words).capitalize() if words else stem
    return HEADER_TEMPLATE.format(name=name, desc=desc,
                                  year=datetime.date.today().year)


def code_only(src):
    """Blank out comments and literals, keeping line structure."""
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append(re.sub(r"[^\n]", " ", src[i:j]))
            i = j
        elif c in "RuUL" and RAW_OPEN.match(src, i):
            m = RAW_OPEN.match(src, i)
            close = ")" + m.group(1) + '"'
            j = src.find(close, m.end())
            j = n if j < 0 else j + len(close)
            out.append(re.sub(r"[^\n]", " ", src[i:j]))
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and src[j] != c and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            j = min(j + 1, n)
            out.append(c + " " * max(j - i - 2, 0) + (c if j - i >= 2 else ""))
            i = j
        else:
            out.append(c)
            i += 1
    return "".join(out)


def literals(src):
    """Yield (offset, body) for each string literal and raw string."""
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            i = n if j < 0 else j + 2
        elif c in "RuUL" and RAW_OPEN.match(src, i):
            m = RAW_OPEN.match(src, i)
            close = ")" + m.group(1) + '"'
            j = src.find(close, m.end())
            j = n if j < 0 else j
            yield m.end(), src[m.end():j]
            i = j + len(close)
        elif c in "\"'":
            j = i + 1
            while j < n and src[j] != c and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            if c == '"':
                yield i + 1, src[i + 1:j]
            i = j + 1
        else:
            i += 1


def check_code(path, src, rules):
    out = []
    rows = src.split("\n")
    if "layout" in rules:
        for ln, row in enumerate(rows, 1):
            if re.match(r"^ *\t", row):
                out.append((ln, "layout", "tab in indentation"))
            if row != row.rstrip():
                out.append((ln, "layout", "trailing whitespace"))
        if src and not src.endswith("\n"):
            out.append((len(rows), "layout", "no newline at end of file"))
        if path.endswith((".h", ".hpp")) and not re.search(
                r"#pragma once|#ifndef\s+\w+\s*\n\s*#define", src):
            out.append((1, "layout", "header has no include guard"))
    if "shipped-comment" in rules and not path.startswith("test/"):
        for start, body in literals(src):
            for m in SHIPPED_COMMENT.finditer(body):
                ln = src.count("\n", 0, start + m.start()) + 1
                out.append((ln, "shipped-comment",
                            f"'{m.group(0)}' in a literal ships to the browser"))
    async_file = matches(path, ASYNC_SCOPE)
    code = code_only(src).split("\n")
    for ln, row in enumerate(code, 1):
        if "restart-call" in rules and RESTART.search(row):
            out.append((ln, "restart-call", "ESP.restart skips saving lifetime and prefs, "
                        "use DeviceInfo::safeRestart"))
        if "async-string" in rules and async_file and STRING.search(row):
            out.append((ln, "async-string", "String allocates on the heap inside network code"))
        if "reserved-name" in rules:
            m = DEFINE.match(row)
            names = [m.group(1)] if m else []
            names += [d.group(1) for d in ANY_DECL.finditer(row) if not DUNDER.match(d.group(1))]
            for name in names:
                if RESERVED.match(name):
                    out.append((ln, "reserved-name", f"{name} is a reserved identifier"))
        if "generic-name" in rules:
            m = LOCAL_DECL.match(row)
            if m and m.group(1) in GENERIC:
                out.append((ln, "generic-name", f"'{m.group(1)}' says nothing about what it holds"))
        if "unsafe-call" in rules:
            for m in UNSAFE.finditer(row):
                out.append((ln, "unsafe-call", f"{m.group(1)}: unbounded or unchecked, use the bounded form"))
        if "float-literal" in rules and not path.startswith("test/"):
            for m in FLOAT_LIT.finditer(row):
                out.append((ln, "float-literal", f"{m.group(1)} is a double, add f"))
        if "mixed-case" in rules:
            for d in ANY_DECL.finditer(row):
                core = re.sub(r"^(?:_+|[msg]_)", "", d.group(1))
                if "_" in core and re.search(r"[a-z][A-Z]", core) and not d.group(1).isupper():
                    out.append((ln, "mixed-case", f"{d.group(1)} mixes snake_case and camelCase"))
    return out


def check_functions(path, src, rules):
    out = []
    commented = set(ln for ln, _, _ in c_comments(src))
    # Lizard misreads R"tag(...)tag" raw strings, so it gets the code with literals blanked.
    code = code_only(src)
    rows = code.split("\n")
    for f in lizard.analyze_file.analyze_source_code(path, code).function_list:
        if "loop-block" in rules and LOOP_FN.search(f.name):
            for ln in range(f.start_line, f.end_line + 1):
                m = BLOCKING.search(rows[ln - 1])
                if m:
                    out.append((ln, "loop-block", f"{m.group(1)}() blocks {f.name}"))
        if "complexity" not in rules:
            continue
        why = []
        if f.cyclomatic_complexity > CCN_MAX:
            why.append(f"complexity {f.cyclomatic_complexity} (max {CCN_MAX})")
        if f.length > LENGTH_MAX:
            why.append(f"{f.length} lines (max {LENGTH_MAX})")
        if f.parameter_count > PARAMS_MAX:
            why.append(f"{f.parameter_count} parameters (max {PARAMS_MAX})")
        if not why and f.cyclomatic_complexity > COMMENT_CCN and \
                not commented & set(range(f.start_line - 3, f.end_line + 1)):
            why.append(f"complexity {f.cyclomatic_complexity} and no comment")
        if why:
            out.append((f.start_line, "complexity", f"{f.name}: " + ", ".join(why)))
    return out


def src_folder(path):
    """First folder under ESPGeiger/src (Corium/X inside Corium), or None outside it."""
    if not path.startswith(SRC_DIR):
        return None
    rest = path[len(SRC_DIR):]
    if rest.startswith(CORIUM):
        rest = rest[len(CORIUM):]
        return CORIUM + rest.split("/", 1)[0] if "/" in rest else None
    return rest.split("/", 1)[0] if "/" in rest else None


def pref_max(name):
    if not PREF_MAX:
        try:
            with open(PREFS_H, encoding="utf-8") as f:
                for m in re.finditer(r"^\s*#\s*define\s+(EGPREF_\w+_MAX)\s+(\d+)", f.read(), re.M):
                    PREF_MAX[m.group(1)] = int(m.group(2))
        except OSError:
            pass
    return PREF_MAX.get(name)


def c_len(lits):
    """Length of adjacent C string literals, an escape counts one."""
    bodies = [s[1:-1] for s in re.findall(C_LIT, lits)]
    return sum(len(re.sub(r"\\(?:x[0-9a-fA-F]{1,2}|.)", "x", b)) for b in bodies)


def check_pref_lens(src):
    """pref-len: ids and option lists fit the buffers import and the form copy them into."""
    out = []
    id_max, opts_max = pref_max("EGPREF_ID_MAX"), pref_max("EGPREF_PATTERN_MAX")
    for rx, cap, what in ((PREF_KEY, id_max, "pref id"), (PREF_GROUP, id_max, "group id"),
                          (PREF_OPTS, opts_max, "options/pattern")):
        if cap is None:
            continue
        for m in rx.finditer(src):
            n = c_len(m.group(1))
            if n > cap:
                ln = src.count("\n", 0, m.start()) + 1
                out.append((ln, "pref-len", f"{what} is {n} chars (max {cap}, EGPrefs.h)"))
    return out


def check_includes(path, src):
    """core-include: Corium stays off app folders, Util stays on Util."""
    folder = src_folder(path)
    if not folder or not folder.startswith(CORIUM):
        return []
    out = []
    for ln, row in enumerate(src.split("\n"), 1):
        m = QUOTED_INCLUDE.match(row)
        if not m:
            continue
        target = os.path.normpath(os.path.join(os.path.dirname(path), m.group(1)))
        to = src_folder(target)
        if to is None and target.startswith("ESPGeiger/") and target not in APP_ROOT_OK:
            out.append((ln, "core-include", f"{folder}/ includes app file {target}"))
            continue
        if to is None or to == folder:
            continue   # beside the file, AppConfig/Version, or a library
        if folder == CORIUM + "Util":
            out.append((ln, "core-include", f"Util includes only Util, not {to}/"))
        elif not to.startswith(CORIUM):
            out.append((ln, "core-include", f"{folder}/ includes app folder {to}/"))
    return out


def core_groups():
    if not CORE_GROUPS:
        for d, _, files in os.walk(CORIUM_DIR):
            for name in files:
                if not name.endswith((".cpp", ".h")):
                    continue
                with open(os.path.join(d, name), encoding="utf-8", errors="replace") as f:
                    CORE_GROUPS.update(m.group(1)[1:-1] for m in PREF_GROUP.finditer(f.read()))
    return CORE_GROUPS


def check_core_prefs(path, src):
    """core-prefs: Corium reads and writes only the pref groups it defines."""
    folder = src_folder(path)
    if not folder or not folder.startswith(CORIUM):
        return []
    out = []
    for m in PREF_CALL.finditer(src):
        if m.group(1) not in core_groups():
            ln = src.count("\n", 0, m.start()) + 1
            out.append((ln, "core-prefs", f"app pref group \"{m.group(1)}\""))
    return out


def suppressed(src):
    """Line -> set of rules silenced by NOLINT markers (empty set = all)."""
    off = {}
    for ln, row in enumerate(src.split("\n"), 1):
        m = NOLINT.search(row)
        if not m:
            continue
        rules = set(r.strip() for r in m.group(2).split(",")) if m.group(2) else set()
        off[ln + 1 if m.group(1) else ln] = rules
    return off


def check_file(path, src, rules):
    out = _check_file(path, src, rules)
    if in_c_scope(path):
        out += check_code(path, src, rules)
        if "core-include" in rules:
            out += check_includes(path, src)
        if "core-prefs" in rules:
            out += check_core_prefs(path, src)
        if "pref-len" in rules and path.startswith(SRC_DIR):
            out += check_pref_lens(src)
        if rules & {"complexity", "loop-block"} and lizard:
            out += check_functions(path, src, rules)
    off = suppressed(src)
    return [f for f in out if not (f[0] in off and (not off[f[0]] or f[1] in off[f[0]]))]


def _check_file(path, src, rules):
    out = []
    is_c = in_c_scope(path)
    if "header" in rules and is_c and not foreign_lib(path) and not has_header(src) \
            and not header_exempt(src):
        out.append((1, "header", "missing GPL licence header"))
    if is_c and "test-name" in rules and path.startswith("test/"):
        for ln, row in enumerate(src.split("\n"), 1):
            m = TEST_DEF.match(row)
            if not m:
                continue
            name = m.group(1)
            if not TEST_NAME.match(name):
                out.append((ln, "test-name", f"{name} is not lower snake case"))
            if len(name) > TEST_NAME_MAX:
                out.append((ln, "test-name", f"{name} is {len(name)} chars (max {TEST_NAME_MAX})"))
    want = rules & {"ascii", "comment-history", "comment-person", "comment-filler",
                    "comment-prefix"}
    if not want:
        return out
    for ln, text in comments(path, src):
        bare = URL.sub(" ", text)
        if "ascii" in want:
            bad = sorted(set(ch for ch in text if ord(ch) > 127))
            if bad:
                shown = " ".join(f"U+{ord(ch):04X}" if 0xDC80 <= ord(ch) <= 0xDCFF
                                 else f"{ch!r} U+{ord(ch):04X}" for ch in bad)
                out.append((ln, "ascii", f"non-ASCII in comment: {shown}"))
        if "comment-history" in want:
            for rx in HISTORY_RE:
                m = rx.search(bare)
                if m:
                    out.append((ln, "comment-history", "'%s'" % m.group(0).strip(" .;")))
                    break
        if "comment-person" in want and lib_of(path) not in UPSTREAM_LIBS:
            for rx in PERSON_RE:
                m = rx.search(bare)
                if m:
                    out.append((ln, "comment-person", f"'{m.group(0)}'"))
                    break
        if "comment-filler" in want:
            m = FILLER.search(bare)
            if m:
                out.append((ln, "comment-filler", f"'{m.group(0)}'"))
            elif MARKDOWN.search(bare):
                out.append((ln, "comment-filler", "markdown bold"))
        if "comment-prefix" in want and PREFIX.match(text):
            out.append((ln, "comment-prefix", f"'{text.split(':')[0]}:' prefix"))
    return out


def added_lines(root, diff_args, untracked=False):
    diff = git("diff", "-U0", "--no-color", "--no-ext-diff", "-M", *diff_args, "--",
               cwd=root)
    added, new_files, cur = {}, set(), None
    is_new = False
    for row in diff.split("\n"):
        if row.startswith("diff --git"):
            is_new, cur = False, None
        elif row.startswith("new file mode") or row == "--- /dev/null":
            is_new = True
        elif row.startswith("+++ "):
            cur = None if row == "+++ /dev/null" else row[6:]
            if cur is not None:
                added.setdefault(cur, set())
                if is_new:
                    new_files.add(cur)
        elif row.startswith("@@") and cur is not None:
            m = re.match(r"@@ -\S+ \+(\d+)(?:,(\d+))? @@", row)
            start, count = int(m.group(1)), int(m.group(2) or 1)
            added[cur].update(range(start, start + count))
    if untracked:
        out = git("ls-files", "-z", "--others", "--exclude-standard", cwd=root)
        for p in out.split("\0"):
            if p:
                new_files.add(p)
                added[p] = None
    return added, new_files


ASCII_FIX = {"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
             "\u2192": "->", "\u2190": "<-", "\u2026": "...", "\u00d7": "x",
             "\u00b1": "+/-", "\u00b5": "u", "\u2264": "<=", "\u2265": ">=",
             "\u00a0": " "}


def guard_name(path):
    stem = re.sub(r"[^A-Za-z0-9]", "_", os.path.basename(path)).upper()
    return "ESPG_" + stem if not stem.startswith("EG") else stem


def fix_file(root, path, src, found):
    """Mechanical fixes for this file's findings -> (text, count)."""
    rows = src.split("\n")
    done = 0
    by_rule = collections.defaultdict(set)
    for ln, rule, msg in found:
        by_rule[rule].add((ln, msg))
    for ln, msg in by_rule["layout"]:
        i = ln - 1
        if msg == "trailing whitespace" and i < len(rows):
            rows[i] = rows[i].rstrip()
            done += 1
        elif msg == "tab in indentation" and i < len(rows):
            ind = re.match(r"^[ \t]*", rows[i]).group(0)
            rows[i] = ind.replace("\t", "  ") + rows[i][len(ind):]
            done += 1
    for ln, msg in by_rule["ascii"]:
        i = ln - 1
        fixed = "".join(ASCII_FIX.get(ch, ch) for ch in rows[i])
        if fixed != rows[i]:
            rows[i] = fixed
            done += 1
    text = "\n".join(rows)
    for ln, msg in by_rule["reserved-name"]:
        m = GUARD.match(rows[ln - 1]) if ln - 1 < len(rows) else None
        if not m or not path.endswith((".h", ".hpp")):
            continue
        old = m.group(1)
        first = re.search(r"^\s*#\s*ifndef\s+(\w+)\s*\n\s*#\s*define\s+\1\b", text, re.M)
        if not first or first.group(1) != old:
            continue
        new = old.lstrip("_")
        clash = subprocess.run(["git", "grep", "-q", "-w", new], cwd=root).returncode == 0
        if not new or clash:
            continue
        text = re.sub(r"(?<!\w)%s(?!\w)" % re.escape(old), new, text)
        done += 1
    if any(msg == "no newline at end of file" for _, msg in by_rule["layout"]):
        text = text.rstrip("\n") + "\n"
        done += 1
    if any(msg == "header has no include guard" for _, msg in by_rule["layout"]):
        g = guard_name(path)
        body = text
        m = re.match(r"(\s*/\*.*?\*/\s*\n)", body, re.S)
        head = m.group(1) if m else ""
        text = head + "#ifndef %s\n#define %s\n\n" % (g, g) + body[len(head):].lstrip("\n")
        text = text.rstrip("\n") + "\n\n#endif\n"
        done += 1
    if by_rule["header"]:
        text = header_block(path) + "\n" + text.lstrip("\n")
        done += 1
    return text, done


FIXABLE = {"layout", "ascii", "reserved-name", "header"}


def lint_tree(args, rules):
    root = git("rev-parse", "--show-toplevel", cwd=HERE).strip()
    FOREIGN_LIBS.update(foreign_libs(root))
    UPSTREAM_LIBS.update(upstream_libs(root, FOREIGN_LIBS))
    if args.staged:
        added, new_files = added_lines(root, ["--cached"])
        files = sorted(added)
        load = lambda p: git("show", ":" + p, cwd=root)
    elif args.commit:
        parent = args.commit + "^"
        if subprocess.run(["git", "rev-parse", "-q", "--verify", parent + "{commit}"],
                          cwd=root, stdout=subprocess.DEVNULL).returncode:
            parent = git("hash-object", "-t", "tree", "/dev/null", cwd=root).strip()
        added, new_files = added_lines(root, [parent, args.commit])
        files = sorted(added)
        load = lambda p: git("show", args.commit + ":" + p, cwd=root)
    else:
        files = list_files(root)
        added, new_files = (added_lines(root, [args.diff], untracked=True)
                            if args.diff else (None, None))
        load = lambda p: read(root, p)
    if args.paths:
        sel = [os.path.relpath(os.path.abspath(p), root) for p in args.paths]
        files = [f for f in files
                 if any(f == s or f.startswith(s.rstrip("/") + "/") for s in sel)]
    findings, fixed, skipped = [], [], []
    args.fixed, args.skipped = fixed, skipped
    for path in files:
        if not (in_c_scope(path) or in_py_scope(path)) or exempt(path):
            continue
        if added is not None and path not in added:
            continue
        src = load(path)
        for ln, rule, msg in check_file(path, src, rules):
            if added is not None:
                if rule == "header":
                    if path not in new_files:
                        continue
                elif added[path] is not None and ln not in added[path]:
                    continue
            findings.append((path, ln, rule, msg))
        mine = [(ln, r, m) for p, ln, r, m in findings if p == path and r in FIXABLE]
        if args.fix and mine:
            current = read(root, path)
            if current != src:
                skipped.append(path)
                continue
            text, n = fix_file(root, path, src, mine)
            if n:
                with open(os.path.join(root, path), "w", encoding="utf-8",
                          errors="surrogateescape", newline="") as f:
                    f.write(text)
                fixed.append((path, n))
                findings = [f for f in findings if f[0] != path]
                for ln, r, m in check_file(path, text, rules):
                    if added is None or added[path] is None or ln in added[path] or \
                            (r == "header" and path in new_files):
                        findings.append((path, ln, r, m))
    return findings


def commit_problems(msg):
    rows = []
    for row in msg.split("\n"):
        if row.startswith("# ------------------------ >8"):
            break
        if not row.startswith("#"):
            rows.append(row.rstrip())
    while rows and not rows[0].strip():
        rows.pop(0)
    while rows and not rows[-1].strip():
        rows.pop()
    if not rows:
        return ["empty message"]
    out = []
    subject, body = rows[0], rows[1:]
    if len(subject) > COMMIT_SUBJECT_MAX and not GIT_MERGE_SUBJECT.match(subject):
        out.append(f"subject is {len(subject)} chars (max {COMMIT_SUBJECT_MAX})")
    if subject.endswith("."):
        out.append("subject ends with a period")
    if body and body[0].strip():
        out.append("no blank line after subject")
    text = [r for r in body if r.strip()]
    if len(text) > COMMIT_BODY_MAX:
        out.append(f"body has {len(text)} lines (max {COMMIT_BODY_MAX})")
    for r in rows:
        if TRAILER.match(r):
            out.append(f"trailer line: '{r.strip()[:60]}'")
        if MARKDOWN.search(r):
            out.append(f"markdown in message: '{r.strip()[:60]}'")
        for rx in COMMIT_EXTRA:
            if rx.search(r):
                out.append(f"local pattern: '{r.strip()[:60]}'")
                break
    bad = sorted(set(ch for ch in "\n".join(rows) if ord(ch) > 127))
    if bad:
        out.append("non-ASCII: " + " ".join(f"U+{ord(ch):04X}" for ch in bad))
    return out


def lint_commits(argv):
    ap = argparse.ArgumentParser(prog="lint_style.py commit-msg")
    ap.add_argument("file", nargs="?")
    ap.add_argument("--log", metavar="RANGE")
    args = ap.parse_args(argv)
    findings = []
    if args.log:
        out = git("log", "--format=%h%x00%B%x01", args.log, cwd=HERE)
        for rec in out.split("\x01"):
            rec = rec.strip("\n")
            if not rec:
                continue
            sha, _, body = rec.partition("\x00")
            for p in commit_problems(body):
                findings.append((sha, None, "commit-msg", p))
    elif args.file:
        with open(args.file, encoding="utf-8", errors="replace") as f:
            for p in commit_problems(f.read()):
                findings.append((args.file, None, "commit-msg", p))
    else:
        ap.error("need FILE or --log RANGE")
    return findings


def report(findings):
    counts = {}
    for path, ln, rule, msg in findings:
        loc = f"{path}:{ln}" if ln is not None else path
        print(f"{loc}: {rule}: {msg}")
        counts[rule] = counts.get(rule, 0) + 1
    if findings:
        print()
        for rule in ALL_RULES:
            if rule in counts:
                print(f"{rule:16} {counts[rule]}")
        print(f"{'total':16} {len(findings)}")
    return 1 if findings else 0


def load_local():
    """Optional per-clone patterns in .git/info/lint_style_extra, one per line:
    `comment REGEX` or `commit REGEX`. Never committed."""
    r = subprocess.run(["git", "rev-parse", "--git-path", "info/lint_style_extra"],
                       cwd=HERE, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True)
    path = os.path.join(HERE, r.stdout.strip())
    if r.returncode or not os.path.isfile(path):
        return
    with open(path, encoding="utf-8") as f:
        for row in f:
            kind, _, rx = row.rstrip("\n").partition(" ")
            if kind not in ("comment", "commit") or not rx:
                continue
            try:
                (HISTORY_RE if kind == "comment" else COMMIT_EXTRA).append(re.compile(rx, re.I))
            except re.error as e:
                print(f"{path}: bad pattern {rx!r}: {e}", file=sys.stderr)


def main(argv):
    load_local()
    if argv and argv[0] == "commit-msg":
        return report(lint_commits(argv[1:]))
    ap = argparse.ArgumentParser(description="ESPGeiger style checks.")
    ap.add_argument("paths", nargs="*")
    ap.add_argument("--diff", metavar="BASE",
                    help="only report lines added relative to BASE")
    ap.add_argument("--staged", action="store_true",
                    help="only report lines added in the index (pre-commit)")
    ap.add_argument("--commit", metavar="REV",
                    help="only report lines added by commit REV")
    ap.add_argument("--rules", help="comma list: " + ",".join(FILE_RULES))
    ap.add_argument("--fix", action="store_true",
                    help="rewrite what can be fixed mechanically: " + ",".join(sorted(FIXABLE)))
    args = ap.parse_args(argv)
    rules = set(FILE_RULES)
    if args.rules:
        rules = set(r.strip() for r in args.rules.split(",") if r.strip())
        unknown = rules - set(FILE_RULES)
        if unknown:
            ap.error("unknown rule: " + ",".join(sorted(unknown)))
    if args.fix and args.commit:
        ap.error("--fix cannot rewrite a commit")
    findings = lint_tree(args, rules)
    rc = report(findings)
    if rules & {"complexity", "loop-block"} and not lizard and not args.staged:
        print("complexity, loop-block: skipped, pip install lizard to check them", file=sys.stderr)
    for path, n in args.fixed:
        print(f"fixed {n} in {path}")
    for path in args.skipped:
        print(f"{path}: has unstaged changes, not fixed")
    if args.fixed:
        print("review the fixes, then git add and commit again")
        return 1
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
