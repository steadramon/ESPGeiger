RAW_OPEN = re.compile(r'(?<![\w])(?:u8|u|U|L)?R"([^()\\\s]{0,16})\(')


def c_comments(src):
    """Yield (line, text, first line of the comment) per comment line."""
    i, n, line = 0, len(src), 1
    while i < n:
        c = src[i]
        if c == "\n":
            line += 1
            i += 1
        elif src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            yield line, src[i + 2:j], line
            i = j
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2)
            j = n if j < 0 else j
            for k, part in enumerate(src[i + 2:j].split("\n")):
                yield line + k, part, line
            line += src.count("\n", i, j)
            i = j + 2
        elif c in "RuUL" and RAW_OPEN.match(src, i):
            m = RAW_OPEN.match(src, i)
            close = ")" + m.group(1) + '"'
            j = src.find(close, m.end())
            j = n if j < 0 else j + len(close)
            line += src.count("\n", i, j)
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and src[j] != c and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            i = j + 1 if j < n and src[j] == c else j
        else:
            i += 1


def py_comments(src):
    try:
        for tok in tokenize.generate_tokens(io.StringIO(src).readline):
            if tok.type == tokenize.COMMENT:
                text = tok.string[1:]
                if tok.start[0] == 1 and text.startswith("!"):
                    continue
                yield tok.start[0], text, tok.start[0]
    except (tokenize.TokenError, IndentationError, SyntaxError):
        return


def comments(path, src):
    gen = py_comments(src) if path.endswith(PY_EXT) else c_comments(src)
    licence_blocks = set()
    rows = list(gen)
    for ln, text, start in rows:
        if start <= HEADER_LINES and FOREIGN_LICENCE.search(text) or HEADER_MARK in text:
            licence_blocks.add(start)
    for ln, text, start in rows:
        if start in licence_blocks and start <= HEADER_LINES:
            continue
        text = text.strip()
        if path.endswith(C_EXT):
            text = re.sub(r"^[/*!<]+\s?", "", text).strip()
        if text:
            yield ln, text


def has_header(src):
    head = "\n".join(src.split("\n", HEADER_LINES)[:HEADER_LINES])
    return HEADER_MARK in head or bool(re.search(r"SPDX-License-Identifier:\s*GPL-[23]\.0", head))


def header_exempt(src):
    head = "\n".join(src.split("\n", HEADER_LINES)[:HEADER_LINES])
    nonblank = sum(1 for ln in src.split("\n") if ln.strip())
    return bool(FOREIGN_LICENCE.search(head)) or nonblank < HEADER_MIN_LINES


def foreign_libs(root):
    """Libraries whose own LICENSE is not the GPL keep their upstream headers."""
    out = set()
    lib = os.path.join(root, "lib")
    names = sorted(os.listdir(lib)) if os.path.isdir(lib) else []
    for name in names:
        d = os.path.join(lib, name)
        if not os.path.isdir(d):
            continue
        for lic in os.listdir(d):
            if not re.match(r"(?:LICEN[CS]E|COPYING)", lic, re.I):
                continue
            with open(os.path.join(d, lic), encoding="utf-8", errors="replace") as f:
                if not GPL_LICENCE.search(f.read(400)):
                    out.add(name)
    return out


def manifest_authors(d):
    names = []
    path = os.path.join(d, "library.json")
    if os.path.isfile(path):
        with open(path, encoding="utf-8", errors="replace") as f:
            try:
                authors = json.load(f).get("authors", [])
            except ValueError:
                authors = []
        for a in authors if isinstance(authors, list) else [authors]:
            names.append(a.get("name", "") if isinstance(a, dict) else str(a))
    path = os.path.join(d, "library.properties")
    if os.path.isfile(path):
        with open(path, encoding="utf-8", errors="replace") as f:
            for row in f:
                if row.startswith("author="):
                    names += row[7:].split(",")
    return [n.strip() for n in names if n.strip()]


def upstream_libs(root, foreign):
    """Libraries taken on from elsewhere: a non-GPL licence or someone else in the manifest."""
    out = set(foreign)
    lib = os.path.join(root, "lib")
    for name in sorted(os.listdir(lib)) if os.path.isdir(lib) else []:
        d = os.path.join(lib, name)
        if os.path.isdir(d) and any(not OWNER.search(a) for a in manifest_authors(d)):
            out.add(name)
    return out


